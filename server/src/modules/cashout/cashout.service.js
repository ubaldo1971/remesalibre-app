import { db } from '../../services/db.service.js';

/**
 * Cashout Service
 * 
 * Manages withdrawals from the system to external worlds (Banks, Cash pickup).
 * Supports:
 * 1. SPEI (Mexican Interbank Transfer) - Simulated
 * 2. OXXO (Cash Pickup) - Simulated reference generation
 */
class CashoutService {

    /**
     * Initiate a cashout request
     * @param {Object} params - Cashout parameters
     * @returns {Promise<Object>} Created request and result
     */
    async requestCashout(params) {
        const {
            user_id,
            amount_mxn,
            method, // 'bank_spei' or 'oxxo'
            destination, // { clabe, bank_name } for SPEI
            pin // For future security check
        } = params;

        console.log(`[CASHOUT] Request: User ${user_id} wants to withdraw $${amount_mxn} MXN via ${method}`);

        // 1. Validate User
        const user = db.findUserById(user_id);
        if (!user) throw new Error('User not found');

        // 2. Validate Balance
        const wallet = db.getWalletByUserId(user_id);
        if (!wallet) throw new Error('Wallet not found');

        const amountNum = parseFloat(amount_mxn);
        if (isNaN(amountNum) || amountNum <= 0) throw new Error('Invalid amount');

        if (wallet.balance_mxn < amountNum) {
            throw new Error(`Insufficient MXN balance. Available: $${wallet.balance_mxn}`);
        }

        // 3. Create Request Record
        const request = db.createCashoutRequest({
            user_id,
            amount_mxn: amountNum,
            method,
            destination: method === 'bank_spei' ? destination : { provider: 'OXXO' }
        });

        try {
            // 4. Lock Funds (Deduct from wallet immediately)
            // We treat this as a debit to the user's wallet
            db.updateWalletBalance(user_id, 'MXN', -amountNum);

            // 5. Update Ledger
            // Debit User Wallet, Credit "Cashout Pending" or "External Provider"
            // For simplicity, we'll credit a system liability account
            db.createLedgerEntry({
                transaction_id: request.id, // Using request ID as tx ID for now
                account_type: 'user_wallet',
                account_id: user_id,
                debit: amountNum,
                credit: 0,
                currency: 'MXN',
                balance_after: wallet.balance_mxn
            });

            db.createLedgerEntry({
                transaction_id: request.id,
                account_type: 'liability',
                account_id: 'system_cashout_pending',
                debit: 0,
                credit: amountNum,
                currency: 'MXN'
            });

            // 6. Process Specific Method Logic
            let processingResult = {};

            if (method === 'bank_spei') {
                processingResult = await this._processSPEI(request);
            } else if (method === 'oxxo') {
                processingResult = await this._processOXXO(request);
            } else {
                throw new Error('Invalid cashout method');
            }

            return {
                success: true,
                request: db.findCashoutRequestById(request.id), // Return updated request
                message: processingResult.message,
                new_balance_mxn: wallet.balance_mxn
            };

        } catch (error) {
            // Rollback if something fails after deduction (simplified)
            // In production, use DB transactions
            console.error('[CASHOUT] Error processing:', error);
            db.updateCashoutRequestStatus(request.id, 'failed', error.message);
            // Refund user
            db.updateWalletBalance(user_id, 'MXN', amountNum);
            throw error;
        }
    }

    /**
     * Simulate SPEI processing
     * @private
     */
    async _processSPEI(request) {
        console.log(`[SPEI] Processing transfer to CLABE: ${request.destination.clabe}`);

        // Simulate bank delay
        await new Promise(resolve => setTimeout(resolve, 1000));

        // Mark as completed (Instant SPEI)
        db.updateCashoutRequestStatus(request.id, 'completed');

        return {
            message: 'Transferencia SPEI procesada exitosamente'
        };
    }

    /**
     * Simulate OXXO reference generation
     * @private
     */
    async _processOXXO(request) {
        console.log(`[OXXO] Generating reference for $${request.amount_mxn}`);

        // OXXO requests stay "pending" until user goes to store
        // In this system, we might mark them as "ready_for_pickup" or keep "pending"
        // The reference code is already generated by db.createCashoutRequest

        return {
            message: 'Referencia OXXO generada. Presenta este código en caja.'
        };
    }

    /**
     * Get user's cashout history
     */
    getHistory(userId) {
        return db.findCashoutRequestsByUserId(userId);
    }
}

export const cashoutService = new CashoutService();
